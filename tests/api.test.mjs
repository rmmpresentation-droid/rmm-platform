import test from 'node:test';
import assert from 'node:assert/strict';
import { newDb } from 'pg-mem';
import request from 'supertest';
import { initialize, createApp } from '../server/app.mjs';

test('connexion, autorisations, isolation et analytique', async () => {
  const memory = newDb();
  const { Pool } = memory.adapters.createPg();
  const pool = new Pool();
  await initialize(pool, 'admin@example.test', 'longpassword123');
  const app = createApp(pool); const root = request.agent(app); const member = request.agent(app); const other = request.agent(app);
  assert.equal((await request(app).get('/api/analytics')).status, 401);
  assert.equal((await root.post('/api/login').send({email:'admin@example.test',password:'incorrect'})).status, 401);
  assert.equal((await root.post('/api/login').send({email:'admin@example.test',password:'longpassword123'})).status, 200);
  for (const email of ['membre@example.test','autre@example.test']) assert.equal((await root.post('/api/users').send({name:'Membre',email,password:'longpassword123',role:'networker'})).status, 201);
  assert.equal((await member.post('/api/login').send({email:'membre@example.test',password:'longpassword123'})).status, 200);
  assert.equal((await other.post('/api/login').send({email:'autre@example.test',password:'longpassword123'})).status, 200);
  assert.equal((await member.get('/api/analytics')).status, 403);
  assert.equal((await member.post('/api/entries/prospects').set('Origin','https://evil.example').send({})).status, 403);
  assert.equal((await root.post('/api/users').send({name:'Test',email:'long@example.test',password:'a'.repeat(73),role:'networker'})).status, 400);
  assert.equal((await member.get('/api/users')).status, 403);
  assert.equal((await member.get('/api/entries/commandes')).status, 403);
  const payload = {title:'Test',detail:'',owner:'',date:'',status:'Premier contact',extra:{phone:'12345678',interest:'Produits'}};
  const created = await member.post('/api/entries/prospects').send(payload); assert.equal(created.status, 201);
  assert.equal((await other.get('/api/entries/prospects')).body.length, 0);
  assert.equal((await other.put(`/api/entries/prospects/${created.body.id}`).send(payload)).status, 404);
  assert.equal((await member.post('/api/entries/prospects').send({...payload,status:'invalide'})).status, 400);
  assert.equal((await root.get('/api/entries/prospects')).body.length, 1);
  assert.equal((await root.get('/api/analytics')).status, 200);
  // Legacy-shaped rows remain readable and allow status updates without new fields.
  const legacyId='80b49dd8-cce9-4f94-a2fa-a724ae33c7f0';
  await pool.query('INSERT INTO entries (id,section,title,detail,status,owner,date,created_by) VALUES ($1,$2,$3,$4,$5,$6,$7,$8)',[legacyId,'prospects','Ancien','', 'Premier contact','','',created.body.created_by]);
  const legacy=(await member.get('/api/entries/prospects')).body.find(x=>x.id===legacyId);
  assert.deepEqual(legacy.extra,{});
  assert.equal((await member.put(`/api/entries/prospects/${legacyId}`).send({...legacy,status:'Présentation'})).status,200);
  assert.equal((await member.post('/api/entries/prospects').send({...payload,extra:{interest:'Produits'}})).status, 400);
  assert.equal((await member.delete(`/api/entries/prospects/${created.body.id}`)).status, 403);
  const presenter = request.agent(app); const stranger = request.agent(app);
  const p = await root.post('/api/users').send({name:'Présentateur',email:'presenter@example.test',password:'longpassword123',role:'presentateur'});
  assert.equal(p.status, 201);
  await root.post('/api/users').send({name:'Autre',email:'presenter2@example.test',password:'longpassword123',role:'presentateur'});
  await presenter.post('/api/login').send({email:'presenter@example.test',password:'longpassword123'});
  await stranger.post('/api/login').send({email:'presenter2@example.test',password:'longpassword123'});
  const meeting = {title:'Présentation',detail:'',owner:'',date:'2026-12-01T10:00',status:'Demandé',extra:{kind:'Présentation',participant:'Test'}};
  assert.equal((await member.post('/api/entries/rendezvous').send({...meeting,status:'Confirmé'})).status, 403);
  const rdv = await member.post('/api/entries/rendezvous').send(meeting); assert.equal(rdv.status,201);
  assert.equal((await member.put(`/api/entries/rendezvous/${rdv.body.id}`).send({...rdv.body,status:'Confirmé'})).status,403);
  assert.equal((await root.put(`/api/entries/rendezvous/${rdv.body.id}`).send({...rdv.body,status:'Confirmé',assigned_to:p.body.id})).status,200);
  assert.equal((await presenter.get('/api/entries/rendezvous')).body.length,1);
  assert.equal((await stranger.get('/api/entries/rendezvous')).body.length,0);
  assert.equal((await presenter.put(`/api/entries/rendezvous/${rdv.body.id}`).send(meeting)).status,404);
  assert.equal((await member.put(`/api/entries/rendezvous/${rdv.body.id}`).send({...rdv.body,status:'Annulé'})).status,403);
  assert.equal((await root.put(`/api/entries/rendezvous/${rdv.body.id}`).send({...rdv.body,status:'Confirmé',assigned_to:''})).status,200);
  assert.equal((await presenter.get('/api/entries/rendezvous')).body.length,0);
  assert.equal((await member.post('/api/logout')).status, 200);
  assert.equal((await member.get('/api/me')).status, 401);
  await pool.end();
});
